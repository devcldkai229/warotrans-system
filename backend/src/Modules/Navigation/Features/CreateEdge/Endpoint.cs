using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Routing;

namespace WaroTrans.Navigation.Features.CreateEdge;

public static class CreateEdgeEndpoint
{
    public static void Map(IEndpointRouteBuilder endpoints)
    {
        endpoints.MapPost("/maps/{mapVersionId:guid}/edges", async (
            Guid mapVersionId,
            CreateEdgeRequest request,
            CreateEdgeHandler handler,
            CancellationToken cancellationToken) =>
        {
            var response = await handler.HandleAsync(mapVersionId, request, cancellationToken);
            return Results.Created($"/api/navigation/edges/{response.Id}", response);
        })
        .WithName("CreateEdge")
        .WithSummary("Create an Edge (Lane) on a draft map version")
        .WithDescription("Draws a logical travel lane as an ordered polyline on a DRAFT MapVersion. An Edge is where a Robot can travel, not a destination. The business code EDGE-NNN is generated by the backend.");
    }
}
