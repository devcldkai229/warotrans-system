import type { ContainerListItem, StorageLocationListItem } from '../../shared/api/warehouseApi';
import type { EndpointDto } from '../../shared/api/navigationApi';
import type { CreateTransportRequestDetailRequest, RequestInputFieldDto } from '../../shared/types/contracts';
import { optionalLevel } from './workflowInputs';

export interface MovementDraft {
  sourceEndpointId: string;
  destinationEndpointId: string;
  destinationStorageLocationId: string;
  destinationLevel: string;
}
export function buildTransportMovements(
  drafts: Record<string, MovementDraft>, containers: ContainerListItem[], locations: StorageLocationListItem[],
  endpoints: EndpointDto[], fields: RequestInputFieldDto[],
): CreateTransportRequestDetailRequest[] {
  return Object.entries(drafts).map(([id, draft], index) => {
    const container = containers.find(c => c.id === id);
    if (!container) throw new Error(`Container ${id} Is Not Eligible In This Warehouse. Refresh Or Remove It.`);
    const sourceLocation = locations.find(l => l.id === container.currentStorageLocationId);
    if (container.currentStorageLocationId && !sourceLocation && !container.currentEndpointId) throw new Error(`Current Storage Location For ${container.barcode} Is Unavailable.`);
    if (sourceLocation && container.currentEndpointId && sourceLocation.endpointId !== container.currentEndpointId) throw new Error(`Current Endpoint And Storage Location Disagree For ${container.barcode}. Refresh Container Data.`);
    const sourceEndpointId = container.currentEndpointId ?? sourceLocation?.endpointId ?? draft.sourceEndpointId;
    if (!endpoints.some(e => e.id === sourceEndpointId && e.isEnabled)) throw new Error(`Select A Valid Source Endpoint For ${container.barcode}.`);
    if (!endpoints.some(e => e.id === draft.destinationEndpointId && e.isEnabled)) throw new Error(`Select A Destination Endpoint For ${container.barcode}.`);
    const destination = locations.find(l => l.id === draft.destinationStorageLocationId);
    if (draft.destinationStorageLocationId && destination?.endpointId !== draft.destinationEndpointId) throw new Error('Destination Storage Location Does Not Belong To This Endpoint.');
    if (draft.destinationLevel.trim() && !draft.destinationStorageLocationId) throw new Error('Select A Destination Storage Location Before Setting A Level.');
    const detail: CreateTransportRequestDetailRequest = {
      sequenceNo: index + 1, containerId: container.id,
      sourceStorageLocationId: container.currentStorageLocationId, sourceEndpointId, sourceLevelNo: container.currentLevelNo,
      destinationStorageLocationId: destination?.id ?? null, destinationEndpointId: draft.destinationEndpointId, destinationLevelNo: optionalLevel(draft.destinationLevel),
    };
    const paths: Record<string, unknown> = {
      containerId: detail.containerId, 'source.endpointId': detail.sourceEndpointId,
      'source.storageLocationId': detail.sourceStorageLocationId, 'source.levelNo': detail.sourceLevelNo,
      'destination.endpointId': detail.destinationEndpointId, 'destination.storageLocationId': detail.destinationStorageLocationId,
      'destination.levelNo': detail.destinationLevelNo,
    };
    for (const field of fields) {
      const key = field.key.replace(/^currentMovement\./i, '');
      // These IDs are generated by queueing, never supplied by staff.
      if (key === 'transportRequestDetailId' || key === 'jobContainerId') continue;
      const value = paths[key];
      if (field.required && (value === null || value === undefined || value === '')) throw new Error(`${field.label} Is Required For ${container.barcode}.`);
    }
    return detail;
  });
}
